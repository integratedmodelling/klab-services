"""Exact native recorded export, atomic publication and deterministic HTTP faults."""
import asyncio
import hashlib

import pytest

from klab_client import AsyncClient, Client, ObservationRequest
from klab_client.errors import AuthorizationError, ProtocolError, TransportError
from klab_simulator.exports import MEDIA, SCHEMA
from klab_simulator.fixtures import authentic_fixture, CROP_SHA
from conftest import launch
from test_vertical import client_args, control, geometry


@pytest.mark.parametrize("query", ["storageEvent=fixture%3Atransition", "storageStart=0&storageEnd=1",
    "storageEvent=fixture%3Amissing&storageStart=0&storageEnd=1",
    "storageEvent=fixture%3Atransition&storageStart=0&storageEnd=1&storageEnd=1",
    "storageEvent=fixture%3Atransition&storageStart=0&storageEnd=1&revision=1"])
def test_temporal_fixture_assignment_refuses_incomplete_duplicate_or_unknown_selection(query):
    from types import SimpleNamespace
    from klab_simulator.exports import export_bytes
    from klab_simulator.state import ContractError
    with pytest.raises(ContractError) as error:
        export_bytes(SimpleNamespace(scenario="nonuniform-export"), {}, "/runtime/export/OBSERVATION/test?" + query)
    assert error.value.status == 422


def request():
    return ObservationRequest("geography:Elevation in m", geometry=geometry(authentic_fixture()))


@pytest.mark.parametrize("mode", ["sync", "async"])
def test_exact_pinned_native_export_preserves_original400cells_and_metadata(mode, tmp_path):
    with launch("usgs-recorded") as ready:
        destination = tmp_path / "recorded-native.tif"
        if mode == "async":
            async def run():
                async with AsyncClient(ready["endpoints"]["runtime"], **client_args(ready)) as client:
                    session = await client.create_session()
                    context = await session.create_context()
                    try:
                        observation = await (await context.observe(request())).result(timeout=2)
                        assert (await client.export_formats(observation))[0].schema_id == SCHEMA
                        return await observation.export_to_file(destination, media_type=MEDIA, max_bytes=2032)
                    finally:
                        await context.release()
                        await session.release()
            result = asyncio.run(run())
        else:
            with Client(ready["endpoints"]["runtime"], **client_args(ready)) as client:
                session = client.create_session()
                context = session.create_context()
                try:
                    observation = context.observe(request()).result(timeout=2)
                    assert client.export_formats(observation)[0].schema_id == SCHEMA
                    result = observation.export_to_file(destination, media_type=MEDIA, max_bytes=2032)
                finally:
                    context.release()
                    session.release()
        # Whole-file identity proves original values, CRS/affine and all metadata
        # were preserved; no expected TIFF is generated by the server/test.
        assert result.bytes_written == 2032
        assert hashlib.sha256(destination.read_bytes()).hexdigest() == CROP_SHA
        assert not list(tmp_path.glob(".klab-export-*"))
        report = control(ready)
        assert not any(report["counts"].values())
        assert all(row["backend"] == "SIMULATED" and row["fixture_origin"] == "AUTHENTIC_FIXTURE_SIMULATED_DELIVERY"
                   for row in report["trace"])


@pytest.mark.parametrize("mode", ["sync", "async"])
@pytest.mark.parametrize("scenario,error", [("export-interrupted", TransportError),
    ("export-media-mismatch", ProtocolError), ("export-denied", AuthorizationError), ("usgs-recorded", ProtocolError)])
def test_failed_stream_never_publishes_partial_file_or_overwrites_existing(mode, scenario, error, tmp_path):
    with launch(scenario) as ready:
        destination = tmp_path / "preserved.tif"
        destination.write_bytes(b"existing user result")
        options = {"media_type": MEDIA, "overwrite": True, "max_bytes": 2031 if scenario == "usgs-recorded" else 4096}
        if mode == "async":
            async def run():
                async with AsyncClient(ready["endpoints"]["runtime"], **client_args(ready)) as client:
                    session = await client.create_session()
                    context = await session.create_context()
                    try:
                        observation = await (await context.observe(request())).result(timeout=2)
                        with pytest.raises(error):
                            await observation.export_to_file(destination, **options)
                        # The stream failure did not create/dispose or cancel the observation.
                        assert (await observation.fetch_data((0,))).values
                    finally:
                        await context.release()
                        await session.release()
            asyncio.run(run())
        else:
            with Client(ready["endpoints"]["runtime"], **client_args(ready)) as client:
                session = client.create_session()
                context = session.create_context()
                try:
                    observation = context.observe(request()).result(timeout=2)
                    with pytest.raises(error):
                        observation.export_to_file(destination, **options)
                    assert observation.fetch_data((0,)).values
                finally:
                    context.release()
                    session.release()
        assert destination.read_bytes() == b"existing user result"
        assert not list(tmp_path.glob(".klab-export-*"))
        report = control(ready)
        assert sum("/export/OBSERVATION/" in row["path"] for row in report["trace"]) == 1
        assert not any(report["counts"].values())
