"""Independent finite raw-datum fixtures, not a codec shared with the SDK.

Golden bytes were generated by fastavro against checked-in Java schema source.
Runtime matching is exact and finite: unknown valid Avro requests also refuse,
not an allegation that Java rejects them. No SDK or oracle dependency at runtime.
"""
import json
from pathlib import Path

from .state import ContractError


def _cases():
    return json.loads((Path(__file__).with_name("fixtures") / "provider-avro.json").read_text(encoding="utf-8"))["cases"]


def submit(state, principal, scope, headers, body):
    if state.scenario != "provider-avro":
        raise ContractError(404, "This finite fixture does not implement provider binary requests")
    root, _ = state._context(scope, principal)
    if principal != "alice" or headers.get("klab-service") != state.service_ids["runtime"]:
        raise ContractError(403, "Synthetic provider principal/origin is not authorized")
    if headers.get("Content-Type", "").split(";", 1)[0].strip().lower() != "application/octet-stream":
        raise ContractError(415, "Provider fixture requires raw Avro datum bytes")
    if len(body) > 1024 * 1024:
        raise ContractError(413, "Finite provider fixture request budget exceeded")
    case = next((case for case in _cases() if bytes.fromhex(case["request_hex"]) == body), None)
    if case is None:
        raise ContractError(422, "Request is outside the declared finite provider fixture; no generic codec or fallback")
    return state._job("resources", root, principal, {"provider_case": case["case"]}), "application/json"


def retrieve(job):
    if job["status"] != "FINISHED":
        raise ContractError(409, "Provider Job has not finished")
    case = next(case for case in _cases() if case["case"] == job["result"]["provider_case"])
    return bytes.fromhex(case["response_hex"]), case["response_media"]
